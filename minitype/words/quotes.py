def bucket(text):
    n = len(text)
    return "short" if n <= SHORT else "medium" if n <= MEDIUM else "long"


class QuoteBank:
    def __init__(self):
        self.online = None    # [(text, source)] once fetched
        self.note = ""

    def _pool(self, source):
        if source == "online":
            if self.online is None:
                try:
                    data = fetch_json(ONLINE_URL, timeout=10)
                    self.online = [(q["text"], q.get("source", ""))
                                   for q in data.get("quotes", []) if q.get("text")]
                    self.note = f"{len(self.online)} online quotes"
                except Exception as e:
                    self.online = []
                    self.note = f"online quotes failed ({type(e).__name__})"
            if self.online:
                return self.online
        return BUILTIN_QUOTES

    def pick(self, length="all", source="built-in", genre="all"):
        """A (text, source) pair of the wanted length and genre, or any if
        none match."""
        pool = self._pool(source)
        if genre != "all":
            by_genre = [q for q in pool if len(q) >= 3 and genre in q[2]]
        else:
            by_genre = pool
        active_pool = by_genre or pool
        fits = [q for q in active_pool if length == "all" or bucket(q[0]) == length]
        chosen = random.choice(fits or active_pool or pool)
        return chosen[0], chosen[1]
